#!/usr/bin/env python3
"""ekkx/yaylib（Go 版）の gen/ から、Dolphin 版のオペレーション表などを作る。

    python tools/gen.py --fetch      # tools/.reference/ に Go のソースを取得してから生成
    python tools/gen.py              # 取得済みのソースから生成

作るもの:
    src/ops_table.dol    オペレーションの表（メソッド・パス・パラメーター・Content-Type）
    src/error_codes.dol  エラーコードの表
    mod.dol              src/mod_head.dol + 全オペレーションの関数（`yaylib.get_timeline[@c, {...}]`）

参照元（MIT）: https://github.com/ekkx/yaylib
"""
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / "tools" / ".reference"
RAW = "https://raw.githubusercontent.com/ekkx/yaylib/master/"
TREE = "https://api.github.com/repos/ekkx/yaylib/git/trees/master?recursive=1"


def fetch():
    REF.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(TREE) as r:
        tree = json.load(r)["tree"]
    wanted = [
        e["path"]
        for e in tree
        if e["type"] == "blob"
        and (
            (e["path"].startswith("gen/api_") and e["path"].endswith(".go"))
            or e["path"] in ("host_routes.go", "error_codes.go")
        )
    ]
    for path in wanted:
        with urllib.request.urlopen(RAW + path) as r:
            (REF / path.replace("/", "__")).write_bytes(r.read())
    print(f"{len(wanted)} files fetched")


def snake(name):
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    return s.lower()


def dol_str(s):
    assert "@" not in s and '"' not in s and "\\" not in s, s
    return '"' + s + '"'


def dol_list(items):
    return "{" + ", ".join(items) + "}"


# ---- Go のオペレーションを読む ----

FUNC = re.compile(r"^func \(a \*(\w+)\) (\w+)Execute\(r (\w+)\) \((?:\*?([\w.\[\]]+), )?\*http\.Response, error\) \{$", re.M)


def parse_ops():
    ops = {}
    for f in sorted(REF.glob("gen__api_*.go")):
        src = f.read_text(encoding="utf-8")
        parts = FUNC.split(src)
        # split: [pre, service, op, req, ret, body, service, ...]
        for i in range(1, len(parts), 5):
            service, op, _req, ret, body = parts[i : i + 5]
            body = body.split("\nfunc ")[0]
            ops[op] = parse_op(service, op, ret, body)
    return ops


def parse_op(service, op, ret, body):
    method = re.search(r"http\.Method(\w+)", body).group(1).upper()
    path = re.search(r'localVarPath := localBasePath \+ "([^"]*)"', body).group(1)
    path_params = re.findall(r'strings\.Replace\(localVarPath, "\{"\+"(\w+)"\+"\}"', body)
    query, form, header = [], [], []
    for kind, name, collection in re.findall(
        r'parameterAddToHeaderOrQuery\((localVar(?:Query|Form|Header)Params), "([^"]+)", [^,]+, "[^"]*", "([^"]*)"\)', body
    ):
        entry = (name, collection)
        target = {"localVarQueryParams": query, "localVarFormParams": form, "localVarHeaderParams": header}[kind]
        if entry not in target:
            target.append(entry)
    body_param = re.search(r"localVarPostBody = r\.(\w+)", body)
    ctypes = re.search(r"localVarHTTPContentTypes := \[\]string\{([^}]*)\}", body).group(1).strip().strip('"')
    return {
        "id": op,
        "service": service,
        "method": method,
        "path": path,
        "path_params": path_params,
        "query": query,
        "form": form,
        "header": header,
        "json_body": bool(body_param),
        "content_type": ctypes or None,
        "returns": ret or "",
    }


def key_of(name):
    """利用者が渡すキー: `file_names[]` → `file_names`、`X-Jwt` → `x_jwt`"""
    return name.removesuffix("[]").lower().replace("-", "_")


def params_table(entries):
    """（キー, ワイヤー上の名前, 配列の送り方）の並び"""
    out = []
    for name, collection in entries:
        mode = "csv" if collection == "csv" else ("multi" if collection == "multi" or name.endswith("[]") else "")
        out.append(f"{{{dol_str(key_of(name))}, {dol_str(name)}, {dol_str(mode)}}}")
    return dol_list(out)


def emit_ops(ops):
    lines = [
        "// Code generated by tools/gen.py; DO NOT EDIT.",
        "// 元: https://github.com/ekkx/yaylib（MIT）の gen/api_*.go",
        "",
        "// オペレーションの表。名前は snake_case。",
        "// query / form は {キー, ワイヤー上の名前, 配列の送り方（\"csv\" \"multi\" \"\"）}、header は {キー, ヘッダー名, \"\"}",
        "ops[] (",
        "    # {",
    ]
    entries = []
    for op in sorted(ops.values(), key=lambda o: snake(o["id"])):
        fields = [
            f'"id": {dol_str(op["id"])}',
            f'"method": {dol_str(op["method"])}',
            f'"path": {dol_str(op["path"])}',
            f'"path_params": {dol_list(dol_str(p) for p in op["path_params"])}',
            f'"query": {params_table(op["query"])}',
            f'"form": {params_table(op["form"])}',
            f'"header": {params_table(op["header"])}',
            f'"json_body": {"true" if op["json_body"] else "false"}',
            f'"content_type": {dol_str(op["content_type"]) if op["content_type"] else "nil"}',
        ]
        entries.append(f'        {dol_str(snake(op["id"]))}: {{' + ", ".join(fields) + "}")
    lines.append(",\n".join(entries))
    lines += ["    }", ")", ""]
    (ROOT / "src" / "ops_table.dol").write_text("\n".join(lines), encoding="utf-8", newline="\n")


def emit_host_routes():
    src = (REF / "host_routes.go").read_text(encoding="utf-8")
    routes = re.findall(r'"([A-Z]+ [^"]+)":\s*"(\w+)"', src)
    lines = [
        "// Code generated by tools/gen.py; DO NOT EDIT.",
        "",
        "// 別のホストで受けるオペレーション（\"METHOD パス\" → ホストの別名）",
        "host_routes[] (",
        "    # {" + ", ".join(f"{dol_str(k)}: {dol_str(v)}" for k, v in routes) + "}",
        ")",
        "",
    ]
    (ROOT / "src" / "host_routes.dol").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return len(routes)


def code_name(name):
    """Required2FA → required_2fa、Incorrect2FA → incorrect_2fa"""
    s = snake(name)
    s = re.sub(r"(?<=[a-z])(?=\d)", "_", s)
    return s.replace("2_fa", "2fa")


def emit_error_codes():
    src = (REF / "error_codes.go").read_text(encoding="utf-8")
    codes = re.findall(r"ErrCode(\w+)\s+ErrorCode\s*=\s*(-?\d+)", src)
    lines = [
        "// Code generated by tools/gen.py; DO NOT EDIT.",
        "",
        "// サーバーのエラーコード（`error_code`）。名前は snake_case",
        "error_codes[] (",
        "    # {" + ",\n        ".join(f"{dol_str(code_name(n))}: {v}" for n, v in codes) + "}",
        ")",
        "",
    ]
    (ROOT / "src" / "error_codes.dol").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return len(codes)


def emit_mod(ops):
    head = (ROOT / "src" / "mod_head.dol").read_text(encoding="utf-8")
    reserved = set(re.findall(r"^(\w+)\[", head, re.M))
    out = [head.rstrip("\n"), "", "// ---- 以下は tools/gen.py が作る（オペレーション） ----", ""]
    for op in sorted(ops.values(), key=lambda o: snake(o["id"])):
        name = snake(op["id"])
        if name in reserved:
            # 手書きの関数（login_with_email など）が優先する
            out += [f"// {name} は src/mod_head.dol の手書きの関数を使う", ""]
            continue
        params = [f"{p}" for p in op["path_params"]]
        doc = [f"// {op['method']} {op['path']}"]
        groups = [
            ("path", op["path_params"]),
            ("query", [key_of(n) for n, _ in op["query"]]),
            ("form", [key_of(n) for n, _ in op["form"]]),
            ("header", [key_of(n) for n, _ in op["header"]]),
        ]
        for label, keys in groups:
            if keys:
                doc.append(f"// {label}: " + ", ".join(keys))
        if op["json_body"]:
            doc.append("// body: body（JSON）")
        out += doc
        out.append(f'{name}[@c, @params = {{:}}] ( # @rt.call[@c, "{name}", @params] )')
        out.append("")
    (ROOT / "mod.dol").write_text("\n".join(out), encoding="utf-8", newline="\n")


def main():
    if "--fetch" in sys.argv:
        fetch()
    if not REF.exists():
        sys.exit("先に `python tools/gen.py --fetch` を実行してください")
    ops = parse_ops()
    emit_ops(ops)
    routes = emit_host_routes()
    codes = emit_error_codes()
    emit_mod(ops)
    print(f"{len(ops)} operations, {routes} host routes, {codes} error codes")


if __name__ == "__main__":
    main()
